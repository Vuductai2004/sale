def _kpi_case(spec: dict) -> dict:
    """One case per SRS section-20 metric: declared formula, scope and missing-data behaviour."""
    name = spec["name"]
    expected = spec["expected"]
    dataset = "kpi_dataset." + _KPI_PATH[spec["group"]]
    release = spec.get("release_blocker", False)
    asserts = [
        name + " equals " + expected + " for the frozen window, recomputed from the raw counter rows with numerator scope '"
        + spec["numerator"] + "' and denominator scope '" + spec["denominator"] + "'.",
        "A recomputation that yields " + spec["bug"] + " is detected as wrong: the stored aggregate and the independent "
        "recomputation must agree before the figure is published.",
        "The dashboard payload for the same tenant and window carries the stored value with its window, coverage and measurement "
        "source; it substitutes neither a design target nor another metric's value.",
        "Boundary behaviour: " + spec["boundary"] + "; missing source data is never rendered as a measured zero.",
    ]
    if release:
        asserts.append(name + " must be exactly 0: any non-zero value blocks the release instead of being reported as a target "
                       "miss waiting for the ASM-002 baseline.")
    return case(
        "GOV-KPI-" + spec["code"],
        spec["code"] + " " + name + ": declared formula, numerator and denominator with honest missing-data behaviour",
        KPI_SUITE, "governance", list(spec["reqs"]),
        ["kpi:" + name] + list(spec["facets"]),
        "baseline", spec["gate"], spec["priority"],
        "The " + name + " figure is produced under different accounting rules - " + spec["bug"] + " - so the KPI is wrong in the "
        "direction that flatters the programme and every decision taken on it inherits the error.",
        [GOV_FX],
        _KPI_PRE + [
            "Metric scope is fixed before measurement: numerator is " + spec["numerator"] + "; denominator is "
            + spec["denominator"] + ".",
            "The dictionary entry for '" + name + "' (owner, unit, window, exclusion rule) is loaded read-only and is compared "
            "with the recomputation instead of being trusted.",
        ],
        {"metric": name, "code": spec["code"], "group": spec["group"], "dataset": dataset,
         "formula": spec["formula"], "window": list(_KPI_WINDOW), "currency": "TWD",
         "expected_value": expected, "wrong_value_if_buggy": spec["bug"],
         "release_blocker": release, "expected_boundary_behaviour": spec["boundary"]},
        [("Compute " + name + " from the frozen rows in " + dataset,
          "The stored aggregate reports " + expected + " and records the formula, the window and the currency that produced it."),
         ("Recompute " + name + " independently from the raw counter rows for the same tenant and window",
          "The recomputed value equals the stored value " + expected + ", and every numerator row lies inside the denominator scope."),
         ("Force the empty-source variant of the metric (no qualifying row in the window)",
          "The metric reports " + spec["boundary"] + "; the display distinguishes missing source data from a measured zero."),
         ("Read the dashboard payload and the metric dictionary entry",
          "The dashboard renders the stored value with its window, coverage and source, and the dictionary names the owner, unit, "
          "numerator and denominator that the recomputation used.")],
        asserts,
        list(spec["forbid"]),
        list(spec["evidence"]),
        ["Delete " + NS + " aggregate, raw-counter and scenario rows for " + spec["code"] + " after exporting the recomputation table."],
        _KPI_AUTO,
        refs=[ANALYTICS, SRS],
    )


