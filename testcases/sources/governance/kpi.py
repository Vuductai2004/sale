def _num(value: float) -> str:
    """Render a synthetic number without trailing zeros: 12000.0 -> '12000', 2.5 -> '2.5'."""
    text = f"{float(value):.4f}".rstrip("0").rstrip(".")
    return text or "0"


def _pct(num: float, den: float) -> str:
    """Percentage of a ratio metric; a zero denominator is NOT_DEFINED, never 0."""
    if not den:
        return "NOT_DEFINED (zero denominator)"
    return f"{round(100.0 * num / den, 1)}%"


def _ratio(num: float, den: float) -> str:
    """Multiplier of a ratio metric; a zero denominator is NOT_DEFINED, never 0."""
    if not den:
        return "NOT_DEFINED (zero denominator)"
    return f"{round(float(num) / den, 2)}x"


def _money(value: float, currency: str = "TWD") -> str:
    return _num(value) + " " + currency


def _total(values: list) -> float:
    return float(sum(values))


def _mean(values: list) -> float:
    return round(_total(values) / len(values), 1)


def _median(values: list) -> float:
    ordered = sorted(values)
    middle = len(ordered) // 2
    if len(ordered) % 2:
        return float(ordered[middle])
    return (ordered[middle - 1] + ordered[middle]) / 2.0


def _p95(values: list) -> float:
    """Nearest-rank 95th percentile, never interpolating a value that was not observed."""
    ordered = sorted(values)
    rank = -(-95 * len(ordered) // 100) or 1
    return float(ordered[rank - 1])


